"""Compiled policy bundles, generated from one source of truth.

Every rule here targets the policy decision input — the shape the gateway
sends:

    {company, agent_id, lifecycle, parent_agent_id, role, run_id,
     workflow, tool, args}

plus, for ephemeral callers, `crew_template`. `role` is the catalog role
for every lifecycle; an ephemeral rule is scoped to one role of one crew,
and the registry's `run_participants` row carries both so the gateway can
inject them with the rest of the verified binding.

Structure: a default-deny `decision`, `allow_rules` and `deny_rules` as
sets, and the lowest-sorting deny wins. Bundles are installed by the
operator and served over the standard OPA bundle API; nothing is pushed at
runtime.

Two bundles per apply:
  - the company bundle, `package poseidon.authz.<company_slug>` — per-company
    so two live companies never claim overlapping OPA bundle roots
    (activation under a shared root would erase the other company's rules);
  - the platform bundle, `package poseidon.platform` — the orchestrator's
    scope is compiler-owned and company-independent, so it compiles
    identically from every blueprint and every operator upsert lands the
    same revision.
The package names and the slug transform come from `common.policy`, which
is also where the gateway and the orchestrator derive the decision paths
they query.
"""

import json
from typing import Any

from common.policy import (
    CREW_REQUEST,
    HEARTBEAT_START,
    MERGE_RESOLVE,
    company_package,
    rego_slug,
)
from compiler.plan import AgentInstanceCR, EphemeralAgentSpec, HeartbeatConfig
from schema.catalog import DOCUMENT_ROLE
from schema.gates import UNDELEGATABLE_PATHS
from schema.tools import RUN_SCOPED

PLATFORM_PACKAGE = "poseidon.platform"

HEADER = """# GENERATED by packages/compiler — do not edit.
# Source: the company blueprint. Change the blueprint and re-apply.
"""

_DECISION = """
package {package}

import rego.v1

# Default deny: a caller with no matching allow rule gets nothing.
default decision := {{"allow": false, "rule": "default_deny"}}

decision := {{"allow": false, "rule": min(deny_rules)}} if {{
	count(deny_rules) > 0
}}

decision := {{"allow": true, "rule": min(allow_rules)}} if {{
	count(deny_rules) == 0
	count(allow_rules) > 0
}}

# Run binding is verified by the gateway against the registry and arrives in
# the input. Policy never reads live data, so OPA stays a pure
# function of bundle + input and restarts are safe.
bound_to_run if {{
	input.run_id != ""
	input.run_binding_verified == true
}}

# Declared empty here so the entrypoint is safe for every blueprint: a
# document configuring no deny-producing policies would otherwise emit a
# bundle OPA refuses to load (`deny_rules` unsafe). Partial sets merge
# across files and an always-false rule contributes nothing.
allow_rules contains "declared_nowhere" if {{ false }}

deny_rules contains "declared_nowhere" if {{ false }}
"""

_ROLE_RULE = """
# {standing_name}: standing {role}.
allow_rules contains "role_{standing_slug}_{tool_slug}" if {{
	input.lifecycle == "standing"
	input.company == "{company}"
	input.role == "{role}"
	input.tool == "{tool}"
{extra}}}
"""

_CREW_RULE = """
# {crew}/{role}: ephemeral {role} of the {crew} crew.
allow_rules contains "crew_{crew_slug}_{role_slug}_{tool_slug}" if {{
	input.lifecycle == "ephemeral"
	input.company == "{company}"
	input.crew_template == "{crew}"
	input.role == "{role}"
	input.tool == "{tool}"
{extra}}}
"""

# The crew.request decision: not a gateway tool but the question the
# platform must win, as the conductor, before it fulfils a run's crew. The
# requested template is narrowed to the conductor's may_spawn list; its
# concurrency cap and the run's budget headroom ride the enriched *input*
# (the platform counts live spawns and checks the ledger; no OPA data
# pushes). There is deliberately no child-⊆-parent scope check (see
# `checks`).
_CREW_REQUEST_RULE = """
# {standing_name}: the crews the platform may fulfil under its authority.
allow_rules contains "role_{standing_slug}_crew_request" if {{
	input.lifecycle == "standing"
	input.company == "{company}"
	input.role == "{role}"
	input.tool == "{crew_request}"
	input.args.crew_template in {may_spawn}
}}
"""

_OVER_CAP_RULE = """
# {agent_id}: at most {cap} concurrent crews (spawn denials are
# first-class governance events).
deny_rules contains "crew_request_over_cap" if {{
	input.tool == "{crew_request}"
	input.agent_id == "{agent_id}"
	input.active_spawns >= {cap}
}}
"""

_NO_BUDGET_RULE = f"""
# No spawn against an exhausted run budget — headroom is verified by the
# platform against the ledger and rides the input.
deny_rules contains "crew_request_no_budget" if {{
	input.tool == "{CREW_REQUEST}"
	input.budget_headroom == false
}}
"""

_PLATFORM = """
# The orchestrator's own privileged calls (the `platform` lifecycle):
# workspace fetch, sandbox registration, the platform verify gate, and the
# merge that only the workflow may perform after the human gate.
allow_rules contains "platform_{tool_slug}" if {{
	input.lifecycle == "platform"
	input.tool == "{tool}"
}}
"""


def _run_binding(tool: str) -> str:
    """RUN_SCOPED tools additionally require a verified run binding — a role
    allow-list without it reopens cross-run tool use. Membership is
    declared in `schema.tools`, a property of the tool, not a name prefix."""
    return "\tbound_to_run\n" if tool in RUN_SCOPED else ""


def _decision_file(package: str, *rules: str) -> str:
    """The bundle's entrypoint file: the default-deny decision, then any
    rules that belong beside it rather than in a per-role file."""
    return HEADER + _DECISION.format(package=package) + "".join(rules)


def _rego_file(company: str, body: str) -> str:
    """The preamble every per-company rule file shares: the do-not-edit
    header, the company package, and the rego.v1 import, then the body."""
    return HEADER + f"\npackage {company_package(company)}\n\nimport rego.v1\n" + body


def _role_file(
    company: str,
    standing_name: str,
    role: str,
    tools: list[str],
    may_spawn: tuple[str, ...] = (),
    agent_id: str = "",
    max_concurrent_spawns: int | None = None,
) -> str:
    body = "".join(
        _ROLE_RULE.format(
            standing_name=standing_name,
            standing_slug=rego_slug(standing_name),
            role=role,
            company=company,
            tool=tool,
            tool_slug=rego_slug(tool),
            extra=_run_binding(tool),
        )
        for tool in sorted(tools)
    )
    if may_spawn:
        body += _CREW_REQUEST_RULE.format(
            standing_name=standing_name,
            standing_slug=rego_slug(standing_name),
            role=role,
            company=company,
            crew_request=CREW_REQUEST,
            may_spawn=json.dumps(sorted(may_spawn)),
        )
        if max_concurrent_spawns:
            body += _OVER_CAP_RULE.format(
                agent_id=agent_id,
                cap=int(max_concurrent_spawns),
                crew_request=CREW_REQUEST,
            )
    return _rego_file(company, body)


def _crew_file(company: str, crew: str, role: str, tools: list[str]) -> str:
    body = "".join(
        _CREW_RULE.format(
            crew=crew,
            crew_slug=rego_slug(crew),
            # Raw in the value comparison — the registry stores the role
            # as written; slugged only in the rule name, like `crew`.
            role=role,
            role_slug=rego_slug(role),
            company=company,
            tool=tool,
            tool_slug=rego_slug(tool),
            extra=_run_binding(tool),
        )
        for tool in sorted(tools)
    )
    return _rego_file(company, body)


def _heartbeat_file(company: str, heartbeat: HeartbeatConfig) -> str:
    """The heartbeat's start authority. `heartbeat.start` is not a gateway
    tool: it is the decision the heartbeat must win before starting a
    workflow on its own initiative; a workflow outside `may_start` falls
    to the default deny — revocation is a blueprint diff.

    The caps are compiled literals and the live counts ride the input,
    verified by the caller — the `active_spawns` idiom: runs in flight,
    today's spend, the target item's prior attempts, and for `scope` the
    repository's open issues. Fail-safe defaults: absent counts deny,
    like the changed-paths rules."""
    allows = "".join(
        f'\nallow_rules contains "heartbeat_start_{rego_slug(workflow)}" if {{\n'
        '\tinput.lifecycle == "platform"\n'
        f'\tinput.company == "{company}"\n'
        f'\tinput.tool == "{HEARTBEAT_START}"\n'
        f'\tinput.args.workflow == "{workflow}"\n'
        "}\n"
        for workflow in sorted(heartbeat.may_start)
    )
    denies = (
        '\ndeny_rules contains "heartbeat_start_over_concurrency" if {\n'
        f'\tinput.tool == "{HEARTBEAT_START}"\n'
        f"\tinput.args.active_runs >= {int(heartbeat.max_concurrent_runs)}\n"
        "}\n"
        '\ndeny_rules contains "heartbeat_start_over_daily_cap" if {\n'
        f'\tinput.tool == "{HEARTBEAT_START}"\n'
        f"\tinput.args.daily_spent_usd >= {json.dumps(heartbeat.daily_cap_usd)}\n"
        "}\n"
        '\ndeny_rules contains "heartbeat_start_over_attempts" if {\n'
        f'\tinput.tool == "{HEARTBEAT_START}"\n'
        f"\tinput.args.attempts >= {int(heartbeat.max_attempts)}\n"
        "}\n"
        # Scoping is refused at the open-ticket cap: the conductor may
        # not flood its own backlog. Only scope reads this count, so only
        # scope fails closed without it.
        '\ndeny_rules contains "heartbeat_start_over_open_tickets" if {\n'
        f'\tinput.tool == "{HEARTBEAT_START}"\n'
        '\tinput.args.workflow == "scope"\n'
        f"\tinput.args.open_tickets >= {int(heartbeat.max_open_tickets)}\n"
        "}\n"
        '\ndeny_rules contains "heartbeat_start_open_tickets_missing" if {\n'
        f'\tinput.tool == "{HEARTBEAT_START}"\n'
        '\tinput.args.workflow == "scope"\n'
        '\tnot is_number(object.get(input, ["args", "open_tickets"], null))\n'
        "}\n"
        # object.get, not a bare reference: negating a builtin over an
        # undefined reference never fires, so a bare `not is_number(...)`
        # would fail open on the absent key it exists to catch.
        '\ndeny_rules contains "heartbeat_start_counts_missing" if {\n'
        f'\tinput.tool == "{HEARTBEAT_START}"\n'
        '\tnot is_number(object.get(input, ["args", "active_runs"], null))\n'
        "}\n"
        '\ndeny_rules contains "heartbeat_start_spend_missing" if {\n'
        f'\tinput.tool == "{HEARTBEAT_START}"\n'
        '\tnot is_number(object.get(input, ["args", "daily_spent_usd"], null))\n'
        "}\n"
        '\ndeny_rules contains "heartbeat_start_attempts_missing" if {\n'
        f'\tinput.tool == "{HEARTBEAT_START}"\n'
        '\tnot is_number(object.get(input, ["args", "attempts"], null))\n'
        "}\n"
    )
    return _rego_file(company, allows + denies)


def _merge_gate_file(
    company: str, delegation: dict[str, Any], policies: dict[str, Any]
) -> str:
    """The policy-resolved merge gate's authority. `merge.resolve` is not a
    gateway tool: it is the decision the review workflow must win before
    merging without a human — the `heartbeat.start` idiom. The three
    caller-verified facts ride the input (the reviewer's verdict, the
    platform's own model-free checks, reviewer-independence from the
    implementer); the delegated class, the carve-outs and the contract
    tree are compiled literals. No delegation compiles no file, so an
    unattended merge with no declared class falls to the default deny —
    revocation is a blueprint diff.

    Fail-safe defaults throughout: the single allow references every input
    it needs, so a missing fact simply never allows; the named denies
    restate each requirement negatively so a refusal is a first-class
    audit story (the rule names the layer that refused), not just an
    unfired allow."""
    paths = json.dumps(sorted(delegation.get("paths") or []))
    carved = json.dumps(
        sorted({*UNDELEGATABLE_PATHS, *(policies.get("deny_paths") or [])})
    )
    contract_paths = sorted((policies.get("contract_tests") or {}).get("paths") or [])
    # A declared contract tree prices its fact into the delegation: the
    # allow additionally requires the platform-composed contract verify
    # (base-ref contract tree over the PR head) to be green. Undeclared,
    # the fact is vacuously absent — the delegation never promised a spec.
    contract_requirement = (
        "\tinput.args.contract_green == true\n" if contract_paths else ""
    )
    contract_deny = (
        # The oracle never merges with the code it certifies: a changed
        # path under the contract tree denies the resolve by its own name —
        # the belt under the validate-time refusal to delegate it, kept
        # separate from the generic carve-out so the audit row names the
        # class that refused.
        '\ndeny_rules contains "merge_resolve_contract_path" if {\n'
        f'\tinput.tool == "{MERGE_RESOLVE}"\n'
        '\tsome path in object.get(input, ["args", "paths"], [])\n'
        f"\tsome contract in {json.dumps(contract_paths)}\n"
        "\tstartswith(path, contract)\n"
        "}\n"
        # The fact restated as a fail-safe named deny, the checks_not_green
        # idiom: object.get so the absent key denies rather than leaving
        # the rule unevaluated.
        '\ndeny_rules contains "merge_resolve_contract_not_green" if {\n'
        f'\tinput.tool == "{MERGE_RESOLVE}"\n'
        '\tobject.get(input, ["args", "contract_green"], false) != true\n'
        "}\n"
        if contract_paths
        else ""
    )
    body = (
        "\npath_delegated(path) if {\n"
        f"\tsome delegated in {paths}\n"
        "\tstartswith(path, delegated)\n"
        "}\n"
        '\nallow_rules contains "merge_resolve_delegated" if {\n'
        '\tinput.lifecycle == "platform"\n'
        f'\tinput.company == "{company}"\n'
        f'\tinput.tool == "{MERGE_RESOLVE}"\n'
        # The quality layers, verified by the caller and riding the
        # input: the independent reviewer's verdict, the platform's own
        # model-free checks, and the registry-checked independence of the
        # reviewer from the implementer. None alone merges anything.
        '\tinput.args.verdict == "pass"\n'
        "\tinput.args.checks_green == true\n"
        "\tinput.args.reviewer_independent == true\n" + contract_requirement +
        # Every changed path fits the delegated class; an empty diff has
        # nothing to delegate and is not a merge policy can resolve.
        "\tcount(input.args.paths) > 0\n"
        "\tevery path in input.args.paths {\n"
        "\t\tpath_delegated(path)\n"
        "\t}\n"
        "}\n"
        # Path rules fail closed, the git.open_pr idiom: without the
        # changed paths in the input the class cannot be checked.
        '\ndeny_rules contains "merge_resolve_paths_missing" if {\n'
        f'\tinput.tool == "{MERGE_RESOLVE}"\n'
        "\tnot input.args.paths\n"
        "}\n"
        # The undelegatable surfaces as a deny — the belt under the
        # compile-time refusal to delegate them: a changed path under a
        # carve-out denies the resolve whatever the delegated class says.
        '\ndeny_rules contains "merge_resolve_carved_out_path" if {\n'
        f'\tinput.tool == "{MERGE_RESOLVE}"\n'
        '\tsome path in object.get(input, ["args", "paths"], [])\n'
        f"\tsome carved in {carved}\n"
        "\tstartswith(path, carved)\n"
        "}\n"
        '\ndeny_rules contains "merge_resolve_undelegated_path" if {\n'
        f'\tinput.tool == "{MERGE_RESOLVE}"\n'
        '\tsome path in object.get(input, ["args", "paths"], [])\n'
        "\tnot path_delegated(path)\n"
        "}\n"
        + contract_deny
        # Each caller-verified fact restated as a fail-safe named deny:
        # object.get, never a bare reference, so the absent key denies
        # rather than leaving the rule unevaluated.
        + '\ndeny_rules contains "merge_resolve_verdict_not_pass" if {\n'
        f'\tinput.tool == "{MERGE_RESOLVE}"\n'
        '\tobject.get(input, ["args", "verdict"], "") != "pass"\n'
        "}\n"
        '\ndeny_rules contains "merge_resolve_checks_not_green" if {\n'
        f'\tinput.tool == "{MERGE_RESOLVE}"\n'
        '\tobject.get(input, ["args", "checks_green"], false) != true\n'
        "}\n"
        '\ndeny_rules contains "merge_resolve_not_independent" if {\n'
        f'\tinput.tool == "{MERGE_RESOLVE}"\n'
        '\tobject.get(input, ["args", "reviewer_independent"], false) != true\n'
        "}\n"
    )
    return _rego_file(company, body)


def _platform_rules(tools: list[str]) -> str:
    return "".join(
        _PLATFORM.format(tool=tool, tool_slug=rego_slug(tool)) for tool in sorted(tools)
    )


def _open_pr_path_deny(
    rule: str, paths: list[str], roles: list[str] | None = None
) -> str:
    """One prefix-ownership deny over `git.open_pr`, named for its class.
    Every path rule the blueprint can write is this shape — any changed
    path under `paths` is refused — so there is one emitter, and the audit
    row reads the same however the refusal was declared. With `roles` the
    declared owner roles are exempt (the contract tree — a caller keyed on
    what it *is*); without, the path is denied outright (`deny_paths`)."""
    owner_clause = f"\tnot input.role in {json.dumps(sorted(roles))}\n" if roles else ""
    return (
        f'\ndeny_rules contains "{rule}" if {{\n'
        '\tinput.tool == "git.open_pr"\n'
        '\tsome path in object.get(input, ["args", "paths"], [])\n'
        f"\tsome prefix in {json.dumps(sorted(paths))}\n"
        "\tstartswith(path, prefix)\n"
        f"{owner_clause}"
        "}\n"
    )


# The tools whose `repo` argument names the repository a call acts on. The
# platform's own calls (`repo.archive`, `git.merge_pr`) are decided by the
# platform bundle and carry no company.
REPO_TOOLS = (
    "git.open_pr",
    "git.read",
    "git.comment",
    "issues.create",
    "issues.read",
    "issues.comment",
)


def _policies_file(
    company: str, policies: dict[str, Any], repo_url: str, documents: dict[str, str]
) -> str:
    """The declared repository, branch protection, deny paths, the
    contract tree and the company's document paths — enforceable on real
    arguments because the gateway passes the call's `repo` and
    bundle-apply already gives policy the changed paths, and which of them
    already exist on the base ref."""
    protection = policies.get("branch_protection") or {}
    protected = protection.get("protected") or []
    pattern = protection.get("allowed_pattern")
    deny_paths = policies.get("deny_paths") or []
    contract = policies.get("contract_tests") or {}
    contract_paths = contract.get("paths") or []

    lines = [
        HEADER,
        f"\npackage {company_package(company)}\n",
        "import rego.v1\n",
        # Lowercased at emit time to match the lowercased input below —
        # `protected: [Main]` must still protect `main`.
        f"\nprotected_branches := {json.dumps(sorted({b.lower() for b in protected}))}\n",
        # An agent works on the company's repository and nothing else: a
        # call naming another one — or none — is denied before the gateway
        # reaches the git host. Fail-closed on a missing argument.
        f"\ndeclared_repo := {json.dumps(repo_url)}\n",
        '\ndeny_rules contains "repo_not_declared" if {\n'
        f"\tinput.tool in {json.dumps(list(REPO_TOOLS))}\n"
        '\tobject.get(input, ["args", "repo"], "") != declared_repo\n'
        "}\n",
    ]
    if protected:
        lines.append(
            '\ndeny_rules contains "git_open_pr_protected_branch" if {\n'
            '\tinput.tool == "git.open_pr"\n'
            "\tlower(input.args.branch) in protected_branches\n"
            "}\n"
        )
    if pattern:
        # json.dumps, never raw interpolation: Rego string literals use
        # JSON escapes, and a raw backtick literal would let a pattern
        # containing a backtick inject policy text into the bundle.
        lines.append(
            '\ndeny_rules contains "git_open_pr_branch_pattern" if {\n'
            '\tinput.tool == "git.open_pr"\n'
            f"\tnot regex.match({json.dumps(pattern)}, input.args.branch)\n"
            "}\n"
        )
    # Path rules fail closed: without the changed paths in the input they
    # cannot be evaluated, so the call is denied. The gateway always
    # supplies args.paths for git.open_pr (bundle-apply computes them
    # before the policy query). Every company has document paths to
    # fence, so the rule is always emitted.
    lines.append(
        '\ndeny_rules contains "git_open_pr_paths_missing" if {\n'
        '\tinput.tool == "git.open_pr"\n'
        "\tnot input.args.paths\n"
        "}\n"
    )
    if deny_paths:
        lines.append(_open_pr_path_deny("git_open_pr_denied_paths", deny_paths))
    if contract_paths:
        # The contract tree is the oracle: only its declared owner roles
        # may deliver into it, so the implementer cannot rewrite the spec
        # its own work is graded by.
        lines.append(
            _open_pr_path_deny(
                "git_open_pr_contract_tree", contract_paths, contract.get("roles") or []
            )
        )
    # The company's documents have one writer: only the steward may
    # deliver into either path. The strategy is written once — a delivery
    # touching it while it already exists on the base ref is denied for
    # the steward too. Presence is a fact the gateway reads off the base
    # ref and passes with the changed paths; a strategy delivery without
    # that fact fails closed. A future standing observer would revise the
    # strategy; nothing in the catalog grows to fill that gap.
    strategy = json.dumps(documents["strategy"])
    lines.append(
        _open_pr_path_deny(
            "git_open_pr_architecture_path", [documents["architecture"]], [DOCUMENT_ROLE]
        )
    )
    lines.append(
        _open_pr_path_deny(
            "git_open_pr_strategy_path", [documents["strategy"]], [DOCUMENT_ROLE]
        )
    )
    lines.append(
        '\ndeny_rules contains "git_open_pr_strategy_present" if {\n'
        '\tinput.tool == "git.open_pr"\n'
        '\tsome path in object.get(input, ["args", "paths_present"], [])\n'
        f"\tstartswith(path, {strategy})\n"
        "}\n"
        '\ndeny_rules contains "git_open_pr_strategy_presence_missing" if {\n'
        '\tinput.tool == "git.open_pr"\n'
        '\tsome path in object.get(input, ["args", "paths"], [])\n'
        f"\tstartswith(path, {strategy})\n"
        "\tnot input.args.paths_present\n"
        "}\n"
    )
    return "".join(lines)


def build_bundle(
    company: str,
    instances: list[AgentInstanceCR],
    ephemeral_agents: list[EphemeralAgentSpec],
    policies: dict[str, Any],
    repo_url: str,
    heartbeat: HeartbeatConfig,
    documents: dict[str, str],
    merge_delegation: dict[str, Any] | None = None,
) -> dict[str, str]:
    """The company bundle: per-role and per-ephemeral-agent files, plus the
    company's decision entrypoint and the blueprint's policy rules — all
    under the company's own package."""
    files = {"authz.rego": _decision_file(company_package(company), _NO_BUDGET_RULE)}
    for instance in instances:
        files[f"role_{rego_slug(instance.standing_name)}.rego"] = _role_file(
            company,
            instance.standing_name,
            instance.role,
            list(instance.tools),
            tuple(instance.may_spawn),
            instance.agent_id,
            instance.max_concurrent_spawns,
        )
    for agent in ephemeral_agents:
        name = f"crew_{rego_slug(agent.crew)}_{rego_slug(agent.role)}.rego"
        files[name] = _crew_file(company, agent.crew, agent.role, list(agent.tools))
    files["policies.rego"] = _policies_file(company, policies, repo_url, documents)
    files["heartbeat.rego"] = _heartbeat_file(company, heartbeat)
    if merge_delegation is not None:
        files["merge_gate.rego"] = _merge_gate_file(company, merge_delegation, policies)
    return files


def build_platform_bundle(platform_tools: list[str]) -> dict[str, str]:
    """The platform bundle: the orchestrator's compiler-owned scope with its
    own decision entrypoint. Identical for every company by construction, so
    every operator upsert of it is a no-op after the first."""
    return {
        "platform.rego": _decision_file(PLATFORM_PACKAGE, _platform_rules(platform_tools))
    }
