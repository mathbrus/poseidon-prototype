"""Compiled policy bundles, generated from one source of truth.

Every rule here targets the §5.1 decision input — the shape the gateway
sends from step 12 on:

    {company, agent_id, lifecycle, parent_agent_id, role, run_id,
     workflow, tool, args}

plus, for ephemeral callers, `crew_template` and `crew_role`. That pair is a
necessary refinement, not an embellishment: §5.1 says `role` carries the
*catalog template*, and `feature-delivery`'s planner and executor both run
the `backend-engineer` template. Without the member name, the planner's
read-only scope and the executor's delivery scope are the same principal to
policy, which would hand every planner `git.open_pr`. The registry already
records both columns on `run_participants`, so the gateway can inject them
with the rest of the verified binding.

Structure mirrors `policies/poc.rego`, which is proven and readable: a
default-deny `decision`, `allow_rules` and `deny_rules` as sets, and the
lowest-sorting deny wins. Bundles are installed by the operator and served
over the standard OPA bundle API; nothing is pushed at runtime (§2b).
"""

import json
from typing import Any

from schema.tools import RUN_SCOPED

PACKAGE = "poseidon.authz"

HEADER = """# GENERATED by packages/compiler — do not edit.
# Source: the company blueprint. Change the blueprint and re-apply.
"""

_DECISION = '''
package {package}

import rego.v1

# Default deny: a caller with no matching allow rule gets nothing.
default decision := {{"allow": false, "rule": "default_deny"}}

decision := {{"allow": false, "rule": min(deny_rules)}} if {{
	count(deny_rules) > 0
}}

decision := {{"allow": true, "rule": min(allow_rules)}} if {{
	count(deny_rules) == 0
	count(allow_rules) > 0
}}

# Run binding is verified by the gateway against the registry and arrives in
# the input (§5.1). Policy never reads live data, so OPA stays a pure
# function of bundle + input and restarts are safe.
bound_to_run if {{
	input.run_id != ""
	input.run_binding_verified == true
}}

# Declared empty here so the entrypoint is safe for every blueprint: a
# document configuring no deny-producing policies would otherwise emit a
# bundle OPA refuses to load (`deny_rules` unsafe). Partial sets merge
# across files and an always-false rule contributes nothing.
allow_rules contains "declared_nowhere" if {{ false }}

deny_rules contains "declared_nowhere" if {{ false }}
'''

_ROLE_RULE = '''
# {hire}: standing hire of the {template} template.
allow_rules contains "role_{hire}_{tool_slug}" if {{
	input.lifecycle == "standing"
	input.company == "{company}"
	input.role == "{template}"
	input.tool == "{tool}"
{extra}}}
'''

_CREW_RULE = '''
# {crew}/{member}: ephemeral crew member on the {template} template.
allow_rules contains "crew_{crew_slug}_{member_slug}_{tool_slug}" if {{
	input.lifecycle == "ephemeral"
	input.company == "{company}"
	input.crew_template == "{crew}"
	input.crew_role == "{member}"
	input.tool == "{tool}"
{extra}}}
'''

_PLATFORM = '''
# The orchestrator's own privileged calls (§5.1 `platform` lifecycle):
# workspace fetch, sandbox registration, the platform verify gate, and the
# merge that only the workflow may perform after the human gate (O-1 A).
allow_rules contains "platform_{tool_slug}" if {{
	input.lifecycle == "platform"
	input.tool == "{tool}"
}}
'''


def _slug(value: str) -> str:
    return value.replace(".", "_").replace("-", "_").replace("/", "_")


def _run_binding(tool: str) -> str:
    """RUN_SCOPED tools additionally require a verified run binding — a role
    allow-list without it reopens cross-run tool use (§5.1). Membership is
    declared in `schema.tools`, a property of the tool, not a name prefix."""
    return "\tbound_to_run\n" if tool in RUN_SCOPED else ""


def _decision_file() -> str:
    return HEADER + _DECISION.format(package=PACKAGE)


def _role_file(company: str, hire: str, template: str, tools: list[str]) -> str:
    body = "".join(
        _ROLE_RULE.format(
            hire=_slug(hire),
            template=template,
            company=company,
            tool=tool,
            tool_slug=_slug(tool),
            extra=_run_binding(tool),
        )
        for tool in sorted(tools)
    )
    return HEADER + f"\npackage {PACKAGE}\n\nimport rego.v1\n" + body


def _crew_file(
    company: str, crew: str, member: str, template: str, tools: list[str]
) -> str:
    body = "".join(
        _CREW_RULE.format(
            crew=crew,
            crew_slug=_slug(crew),
            # Raw in the value comparison — `run_participants.crew_role`
            # stores the member name as written; slugged only in the rule
            # name, like `crew` and `template`.
            member=member,
            member_slug=_slug(member),
            template=template,
            company=company,
            tool=tool,
            tool_slug=_slug(tool),
            extra=_run_binding(tool),
        )
        for tool in sorted(tools)
    )
    return HEADER + f"\npackage {PACKAGE}\n\nimport rego.v1\n" + body


def _platform_file(tools: list[str]) -> str:
    body = "".join(
        _PLATFORM.format(tool=tool, tool_slug=_slug(tool)) for tool in sorted(tools)
    )
    return HEADER + f"\npackage {PACKAGE}\n\nimport rego.v1\n" + body


def _policies_file(policies: dict[str, Any]) -> str:
    """Branch protection, deny paths and path ownership — enforceable on
    real arguments because bundle-apply already gives policy the changed
    paths (§4.7)."""
    protection = policies.get("branch_protection") or {}
    protected = protection.get("protected") or []
    pattern = protection.get("allowed_pattern")
    deny_paths = policies.get("deny_paths") or []
    ownership = policies.get("path_ownership") or []

    lines = [
        HEADER,
        f"\npackage {PACKAGE}\n",
        "import rego.v1\n",
        # Lowercased at emit time to match the lowercased input below —
        # `protected: [Main]` must still protect `main`.
        f"\nprotected_branches := {json.dumps(sorted({b.lower() for b in protected}))}\n",
        f"\ndeny_paths := {json.dumps(sorted(deny_paths))}\n",
    ]
    if protected:
        lines.append(
            '\ndeny_rules contains "git_open_pr_protected_branch" if {\n'
            '\tinput.tool == "git.open_pr"\n'
            "\tlower(input.args.branch) in protected_branches\n"
            "}\n"
        )
    if pattern:
        # json.dumps, never raw interpolation: Rego string literals use
        # JSON escapes, and a raw backtick literal would let a pattern
        # containing a backtick inject policy text into the bundle.
        lines.append(
            '\ndeny_rules contains "git_open_pr_branch_pattern" if {\n'
            '\tinput.tool == "git.open_pr"\n'
            f"\tnot regex.match({json.dumps(pattern)}, input.args.branch)\n"
            "}\n"
        )
    if deny_paths or ownership:
        # Path rules fail closed: without the changed paths in the input
        # they cannot be evaluated, so the call is denied. The gateway
        # always supplies args.paths for git.open_pr (bundle-apply
        # computes them before the policy query).
        lines.append(
            '\ndeny_rules contains "git_open_pr_paths_missing" if {\n'
            '\tinput.tool == "git.open_pr"\n'
            "\tnot input.args.paths\n"
            "}\n"
        )
    if deny_paths:
        lines.append(
            '\ndeny_rules contains "git_open_pr_denied_paths" if {\n'
            '\tinput.tool == "git.open_pr"\n'
            '\tsome path in object.get(input, ["args", "paths"], [])\n'
            "\tsome denied in deny_paths\n"
            "\tstartswith(path, denied)\n"
            "}\n"
        )
    for index, rule in enumerate(ownership):
        # Path ownership names role *templates* — what a caller is, not
        # which instance it happens to be (§4.5 rule 3).
        roles = json.dumps(sorted(rule.get("roles") or []))
        paths = json.dumps(sorted(rule.get("paths") or []))
        lines.append(
            f'\ndeny_rules contains "git_open_pr_path_ownership_{index}" if {{\n'
            '\tinput.tool == "git.open_pr"\n'
            f"\tsome path in object.get(input, [\"args\", \"paths\"], [])\n"
            f"\tsome owned in {paths}\n"
            "\tstartswith(path, owned)\n"
            f"\tnot input.role in {roles}\n"
            "}\n"
        )
    return "".join(lines)


def build_bundle(
    company: str,
    instances: list[Any],
    crew_members: list[Any],
    policies: dict[str, Any],
    platform_tools: list[str],
) -> dict[str, str]:
    """The per-role and per-crew-member files, plus the shared decision
    entrypoint and the blueprint's policy rules."""
    files = {"authz.rego": _decision_file()}
    for instance in instances:
        files[f"role_{_slug(instance.hire)}.rego"] = _role_file(
            company, instance.hire, instance.role_template, list(instance.tools)
        )
    for member in crew_members:
        name = f"crew_{_slug(member.crew)}_{_slug(member.member)}.rego"
        files[name] = _crew_file(
            company, member.crew, member.member, member.role_template, list(member.tools)
        )
    files["platform.rego"] = _platform_file(platform_tools)
    files["policies.rego"] = _policies_file(policies)
    return files
